const simulationWalkSource = `---- MODULE M ----
VARIABLE x
Init == x = 0
A == /\ x = 0 /\ x' \in {1, 2}
B == /\ x = 1 /\ x' \in {0, 2}
C == /\ x = 2 /\ x' \in {0, 1, 2}
Disabled == FALSE
Next == A \/ Disabled \/ B \/ C
====
`

func TestJavaTLCSimulationWorkerWalk(t *testing.T) {
	// Java TLC 1.7.4, seed 1. Each row contains all states generated by the
	// chosen action followed by the randomly selected successor.
	want := []string{
		"WALK\t1\t2\t=>\t2", "WALK\t0\t1\t2\t=>\t1", "WALK\t0\t2\t=>\t0", "WALK\t1\t2\t=>\t2",
		"WALK\t0\t1\t2\t=>\t2", "WALK\t0\t1\t2\t=>\t2", "WALK\t0\t1\t2\t=>\t0", "WALK\t1\t2\t=>\t2",
		"WALK\t0\t1\t2\t=>\t2", "WALK\t0\t1\t2\t=>\t1", "WALK\t0\t2\t=>\t0", "WALK\t1\t2\t=>\t2",
		"WALK\t0\t1\t2\t=>\t1", "WALK\t0\t2\t=>\t2", "WALK\t0\t1\t2\t=>\t1", "WALK\t0\t2\t=>\t0",
		"WALK\t1\t2\t=>\t1", "WALK\t0\t2\t=>\t0", "WALK\t1\t2\t=>\t2", "WALK\t0\t1\t2\t=>\t2",
	}
	got := simulationWalk(t, 1)
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("Go walk %q; want Java 1.7.4 walk %q", got, want)
	}
	if jar := os.Getenv("TLC_JAR"); jar != "" {
		classes := compileSimulationOracle(t, jar)
		for _, seed := range []int64{0, 1, -42, 918273} {
			t.Run(fmt.Sprint(seed), func(t *testing.T) {
				got := simulationWalk(t, seed)
				want := javaSimulationWalk(t, jar, classes, seed)
				if !reflect.DeepEqual(got, want) {
					t.Fatalf("Go walk %q; Java walk %q", got, want)
				}
			})
		}
	}
}

func simulationWalk(t *testing.T, seed int64) []string {
	t.Helper()
	module, err := parser.ParseModule(simulationWalkSource)
	if err != nil {
		t.Fatal(err)
	}
	cfg, err := config.Parse("INIT Init NEXT Next")
	if err != nil {
		t.Fatal(err)
	}
	model, err := prepare(module, cfg)
	if err != nil {
		t.Fatal(err)
	}
	model.ctx = context.Background()
	actions, err := model.simulationActions()
	if err != nil {
		t.Fatal(err)
	}
	worker := newSimulationWorker(model, actions, evaluator.NewJavaRandom(seed))
	zero, _ := value.Integer(0)
	state := worker.randomState([]evaluator.State{{"x": zero}})
	var result []string
	for range 20 {
		states, err := worker.nextStates(state)
		if err != nil {
			t.Fatal(err)
		}
		if len(states) == 0 {
			return append(result, "WALK\tdeadlock")
		}
		row := "WALK"
		for _, next := range states {
			row += "\t" + next["x"].String()
		}
		state = worker.randomState(states)
		result = append(result, row+"\t=>\t"+state["x"].String())
	}
	return result
}

func javaSimulationWalk(t *testing.T, jar, classes string, seed int64) []string {
	t.Helper()
	dir := t.TempDir()
	for name, text := range map[string]string{"M.tla": simulationWalkSource, "M.cfg": "INIT Init\nNEXT Next\nCHECK_DEADLOCK FALSE\n"} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(text), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	cmd := exec.Command("java", "-Djava.io.tmpdir="+t.TempDir(), "-Xmx256m", "-cp", jar+string(os.PathListSeparator)+classes, "RandomWalk", fmt.Sprint(seed))
	cmd.Dir = dir
	javatmp.Apply(cmd)
	output, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("Java simulation oracle: %v\n%s", err, output)
	}
	var result []string
	for line := range strings.Lines(string(output)) {
		if strings.HasPrefix(line, "WALK\t") {
			result = append(result, strings.TrimSpace(line))
		}
	}
	return result
}
